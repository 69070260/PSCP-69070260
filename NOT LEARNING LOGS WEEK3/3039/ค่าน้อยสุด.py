"""โปรแกรมหาค่าน้อยสุด 4 ค่า"""
def main():
    """หาค่าน้อยที่สุดใน 4 ค่า"""
    n = int(input())
    n2 = int(input()) #อันนี้คือค่าน้อยที่สุด เด๋วเอาไปเทียบกับ for loop ด้านล่าง

    for _ in range(n-1):
        x = int(input())
        if x < n2: #ถ้า x ที่รับมามีค่าน้อยกว่า n2 ให้ n2 มีค่าเท่า x เลย
            n2 = x

    print(n2)

main()
